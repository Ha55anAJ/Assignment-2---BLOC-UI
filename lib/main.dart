import 'dart:async';
import 'dart:developer';

import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';

import 'app.dart';
import 'features/items/data/datasources/item_remote_data_source.dart';
import 'features/items/data/repositories/item_repository_impl.dart';
import 'features/items/domain/usecases/seed_items.dart';
import 'firebase_options.dart';

Future<void> main() async {
  // Firebase.initializeApp talks to the platform through plugins, so the
  // Flutter binding has to be ready before it runs.
  WidgetsFlutterBinding.ensureInitialized();

  // Connect to the Firebase project. `DefaultFirebaseOptions` was generated by
  // `flutterfire configure` and picks the right config for the platform.
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);

  // Wire the layers together: Firestore feeds the data source, the data
  // source feeds the repository, and the repository is handed to the app.
  final repository = ItemRepositoryImpl(
    remoteDataSource: ItemRemoteDataSource(
      firestore: FirebaseFirestore.instance,
    ),
  );

  // One-time seed of the sample items from the brief. It is not awaited, so
  // the app opens straight away; the items then arrive through the live list.
  unawaited(
    SeedItems(repository)().then(
      (seeded) {
        if (seeded) log('Wrote the sample items', name: 'main');
      },
      onError: (Object error) {
        log('Could not seed the sample items: $error', name: 'main');
      },
    ),
  );

  runApp(LostFoundApp(repository: repository));
}
